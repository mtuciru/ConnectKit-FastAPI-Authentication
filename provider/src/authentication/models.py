class User(AsyncAttrs, Base):
    """
    OAuth2 User is basic user data representation.
    It's include:
        login -- identifier username from small subset of allowed chars (a-zA-Z0-9_-) and some simple rules
            It's used as human-readable alternative inner user id
            This value by default used for login process
        email -- primary email address can be verified or non-verified
            If it verified (verification process lies outside the scope of this library) can be used as login
            Also this value will be returned in id_token and userinfo if requested
            (you can store additional emails, but they will not be used by this library)
        phone -- phone number can be verified or non-verified
            If it verified (verification process lies outside the scope of this library) can be used as login
            Also this value will be returned in id_token and userinfo if requested
            (you can store additional phone numbers, but they will not be used by this library)
        scope -- user scopes (access rules)
            This library define some specific values for this work and some values defined by openid connect
            You can use you're own scope values in app logic
        active -- status of activation of account
            When active is False, user can login to provider, but:
                - He can't authorize third-party clients
                - He can't interact with transparent apps (only provider frontend allowed)
                - He can't interact any resource servers
                - He can only resieve userinfo from /userinfo endpoint
            This state of user created for:
                - User can see that it's account present in system (can see user profile page),
                    but wait when verification process completed
                    (Some users being confused when they registered on site and can not login to it)
    """
    __tablename__ = "oauth2_user"
    id: Mapped[int] = mapped_column(primary_key=True)
    # Unique alphanumeric user identification (aka username)
    login: Mapped[str] = mapped_column(nullable=False, unique=True, index=True)
    # Primary email. Can be used as login for authentification
    # Returned as userinfo email field
    email: Mapped[str] = mapped_column(nullable=True, unique=True, index=True)
    email_verified: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    # Primary phone number. Can be used as login for authentification
    # Returned as userinfo phone_number field
    phone: Mapped[str] = mapped_column(nullable=True, unique=True, index=True)
    phone_verified: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    # User space-delimited scope (his rights)
    scope: Mapped[str] = mapped_column(nullable=False)
    # External authenticated users can haven't password
    _password: Mapped[str] = mapped_column("password", nullable=True)
    # Inactive account can success login in provider but can't interact with system
    # Frontend can display user home page.
    active: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")

    created_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False,
                                                 server_default=func.current_timestamp())
    password_changed_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False,
                                                          server_default=func.current_timestamp())
    # Last time primary email or phone updated
    updated_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False,
                                                 server_default=func.current_timestamp())

    @hybrid_property
    def password(self):
        return ""

    @password.setter
    def password(self, value: str):
        self._password = _hasher.hash(value)

    @hybrid_property
    def scopes(self):
        return self.scope.split()

    @scopes.setter
    def scopes(self, value: list[str]):
        self.scope = " ".join(value)

    @hybrid_method
    def verify_password(self, value: str):
        try:
            _hasher.verify(self._password, value)
            if _hasher.check_needs_rehash(self._password):
                self._password = _hasher.hash(value)
            return True
        except Argon2Error:
            return False


class UserLock(AsyncAttrs, Base):
    """
    On this table login system locked per user login (for change simultaneous tries to linear for counters)
    """
    __tablename__ = 'oauth2_user_lock'
    id: Mapped[int] = mapped_column(ForeignKey("oauth2_user.id", ondelete="CASCADE"), primary_key=True)
    # LOGIN
    # list of allowed primary methods for End-User authentication. Default: pwd (password)
    login_via: Mapped[str] = mapped_column(nullable=False, server_default="pwd")
    # list of allowed external client_id via that login allowed.
    # Note: external login disable mfa and reauthenticate methods for session, these allowed only via same external.
    # Note: external login not allowed:
    #   - if End-User not enable this external method.
    #   - if End-User not exists in system (in this case registration flow will be started)
    login_via_external: Mapped[str] = mapped_column(nullable=False, server_default="")
    # login attempts count
    login_attempt_count: Mapped[int] = mapped_column(nullable=False, server_default="0")
    # Last login (for reset counter if last attempt will be very old)
    login_last_attempt_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=True)
    # MFA
    # Enabled mfa methods.
    # In this column specified additional methods, that will be performed to validate session.
    # session without completed mfa not allow any operations exclude mfa.
    # https://www.iana.org/assignments/authentication-method-reference-values/authentication-method-reference-values.xhtml
    # If you use alternative main authorization method (instead of password), don't add it to this column:
    # it's only for ADDITIONAL methods (after successful main method)
    # list of allowed secondary methods for End-User authentication. One of this must be completed.
    mfa_via: Mapped[str] = mapped_column(nullable=False, server_default="")
    # mfa attempts count
    mfa_attempt_count: Mapped[int] = mapped_column(nullable=False, server_default="0")
    # Last mfa (for reset counter if last attempt will be very old)
    mfa_last_attempt_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=True)
    # REAUTHENTICATE
    # Only for provider sessions
    # Process of reauthentication required confirmation via one of 'mfa_via' or 'login_via' method by default
    # If you want constraint allowed methods, set it in reauthenticate_via
    # Use this counter for reauthenticate process. (For separate this counter of login counter)
    # If you realize own reauthenticate method, call reauthenticate_callback with status for mark failed and successful reauthentication
    # reauthenticate attempts count
    reauthenticate_attempt_count: Mapped[int] = mapped_column(nullable=False, server_default="0")
    # Last reauthenticate (for reset counter if last attempt will be very old)
    reauthenticate_last_attempt_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=True)
    # BLOCK
    # User block status. If blocked, error returned when login will be tried.
    # If you realise custom main auth methods, don't forget check block status of user.
    block: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    block_reason: Mapped[str] = mapped_column(nullable=True)
    deleted: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")


