    emit_refresh_token: Mapped[bool] = mapped_column(nullable=False, server_default="TRUE")
    # Enabled or disabled rotating refresh tokens. refresh_token grant will discard old token and create new
    rotate_refresh_token: Mapped[bool] = mapped_column(nullable=False, server_default="TRUE")
    # Space-delimited default (and interpret as minimal) scope values (End-User must allow all of this)
    # If client explicit request less scopes that it's presented, explicit scope will be used
    scope: Mapped[str] = mapped_column(nullable=False, server_default="")
    # Space-delimited max scope values that this client can request
    # If client explicit request more scopes than max_scopes, provider may truncate scopes or reject request
    max_scope: Mapped[str] = mapped_column(nullable=True)
    # \n-separated list of registered redirect_uris for client (used only for 'authorization_code' and 'implicit')
    # If contains only one redirect_uri, it is interpreting as default value
    _redirect_uris: Mapped[str] = mapped_column(nullable=True)
    # Special client, if True grant_type must be 'password'
    # and 'scope', 'redirect_uris', 'for_user_id', lifetimes, 'reauthenticated_at' ignored (derived from frontend)
    # Client acts as user-agent (provider frontend)
    # Used as alternative variant for browser-based system applications.
    # Don't set this flag for third-party clients
    transparent: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    # Redefines timing
    # Lifetime of our access token in minutes. Must be smaller
    access_lifetime: Mapped[int] = mapped_column(nullable=True)
    # Lifetime of our refresh token in hours. Session live time
    refresh_lifetime: Mapped[int] = mapped_column(nullable=True)
    # Authentication max_age in seconds. Time after that required reauthentication for sensitive operations.
    auth_max_age: Mapped[int] = mapped_column(nullable=True)
    # Enable token bounds settings
    access_ip_bound: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    refresh_ip_bound: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    dpop_bound: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    # ID of sector for pairwise sub generation
    # (if not specified, 'public' sub will be used (user.id int value converted to str)
    pairwise_sector_id: Mapped[int] = mapped_column(ForeignKey("oauth2_sector_identifier.id"), nullable=True)
    # Authorized party id. ID describe group of logically bound clients (from the same owner for example)
    azp_id: Mapped[int] = mapped_column(ForeignKey("oauth2_azp_identifier.id"), nullable=True)
    # Enable userinfo settings
    userinfo_as_jwt: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")

    @hybrid_property
    def client_secret(self):
        return "" if self._client_secret is not None else None

    @client_secret.setter
    def client_secret(self, value: str):
        self._client_secret = _hasher.hash(value)

    @hybrid_property
    def scopes(self):
        return self.scope.split()

    @scopes.setter
    def scopes(self, value: list[str]):
        self.scope = " ".join(value)

    @hybrid_property
    def max_scopes(self):
        return self.max_scope.split()

    @max_scopes.setter
    def max_scopes(self, value: list[str]):
        self.max_scope = " ".join(value)

    @hybrid_property
    def response_types(self) -> list[ResponseType]:
        lst = self._response_types.split(";")
        return list(map(ResponseType, lst))

    @response_types.setter
    def response_types(self, value: list[ResponseType]):
        self._response_types = ";".join(map(str, value))

    @hybrid_property
    def redirect_uris(self) -> list[str]:
        lst = self._redirect_uris.split("\n")
        return lst

    @redirect_uris.setter
    def redirect_uris(self, value: list[str]):
        self._redirect_uris = "\n".join(value)

    @hybrid_method
    def verify_client_secret(self, value: str) -> bool:
        try:
            _hasher.verify(self._client_secret, value)
            if _hasher.check_needs_rehash(self._client_secret):
                self._client_secret = _hasher.hash(value)
            return True
        except Argon2Error:
            return False


