# -*- Session definitions -*-

# Exists three types of session:
#   - OAuth2ProviderSession
#   - OAuth2UserSession
#   - OAuth2ClientSession
# OAuth2ProviderSession:
#   This session obtained direct by user via user-agent or transparent system client (acts like user-agent)
#   Provider frontend via special client_id 'frontend' call /token endpoint with login/password pair to authenticate user
#   In this case reauthentication process must be performed via 2fa (if enabled) or password without login.
#   Also, provider frontend may initial external provider authentification for obtain user information instead login/password.
#   In this case reauthentication process must be performed via the same external provider (password and 2fa not allowed)
#   For transparent system client (like mobile/native app with login/password) allowed only password grant (and 2fa)
#   Session obtained from this app can't be used as master session for other client authentication.
# OAuth2UserSession:
#   This session obtained by client via authorization endpoint by redirecting to provider frontend.
#   For such clients not exists long session flags, refresh token always has the same expiration time
#   Also for this clients may enable ip constrains
# OAuth2ClientSession:
#   This session obtained by client for itself.
#   Used for service authorization in system for request other services.
#   Can be used for revoke and introspect endpoints
#
# uid value of session is unique for all sessions (all types)

class OAuth2ProviderSession(AsyncAttrs, Base):
    """
    Provider session.
    Created if:
        - Special client_id == 'frontend', grant_type == 'password'
        - External provider authorization process (additional oauth2_external_state record created)
        - System transparent client: grant_type == 'password'
          In this case client acts as user with user scopes.
          Third-party client must not be system client
    Only two first types authentication may be as master for user session (because they embedded to provider)
    This type of session may use DPoP tokens if supported by frontend.
    You can require use of DPoP for provider sessions, but you must add support for creation DPoP tokens in frontend.
    """
    __tablename__ = 'oauth2_provider_session'
    # Generated by /oauth/token endpoint whew first session access token created (or external_client_pipeline)
    uid: Mapped[str] = mapped_column(primary_key=True)
    # Authenticated user id
    user_id: Mapped[int] = mapped_column(ForeignKey("oauth2_user.id", ondelete='CASCADE'), nullable=False)
    # Authenticated system client id
    client_id: Mapped[int] = mapped_column(ForeignKey("oauth2_client.id", ondelete="CASCADE"), nullable=True)
    # External client id
    # ForeignKey("oauth2_external_client.id", ondelete="CASCADE")
    external_client_id: Mapped[int] = mapped_column(nullable=True)
    # Control refresh token validity (only one valid refresh token per session) (for frontend exists always)
    refresh_token_jti: Mapped[str] = mapped_column(nullable=False)
    # Creation time
    started_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False,
                                                 server_default=func.current_timestamp())
    # Expire time (updated on refresh process)
    expire_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False)
    # Last time when reauthentication done (used for process max_age parameter)
    reauthenticated_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=False,
                                                         server_default=func.current_timestamp())
    # Mark that need use 'long' expiration time for expire_at (long-lived session without user activity)
    long_session: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    # Fingerprint tell the same browser and ip (may empty if system client)
    fingerprint: Mapped[str] = mapped_column(nullable=False)
    # dpop_jkt
    dpop_jkt: Mapped[str] = mapped_column(nullable=True)
    # Space-delimited amr values. Always contains primary method reference (or amr list from external client)
    amr: Mapped[str] = mapped_column(nullable=False, server_default="")
    # list of allowed reauthenticate methods for End-User authentication. One of this must be completed.
    reauthenticate_via: Mapped[str] = mapped_column(nullable=False, server_default="")
    # Partial authenticated session, waiting for mfa complete
    mfa_waiting: Mapped[bool] = mapped_column(nullable=False, server_default="FALSE")
    # Expire time for incomplete session (if mfa not completed before this time, session closed)
    expire_mfa_at: Mapped[datetime] = mapped_column(TIMESTAMP(timezone=True), nullable=True)


class OAuth2UserSession(AsyncAttrs, Base):
    """
    User session via client.

    ps_uid is provider session via that client obtain authentification
    If ps_uid session will be closed, any children sessions also will be closed.
    This value not setting if:
        - Requested offline refresh (offline_refresh allows session without master session)
    """
    __tablename__ = 'oauth2_user_session'
    # Generated by /oauth/token endpoint whew first session access token created (or external_client_pipeline)
    uid: Mapped[str] = mapped_column(primary_key=True)
    # Provider session uid
    ps_uid: Mapped[str] = mapped_column(ForeignKey("oauth2_provider_session.uid", ondelete='CASCADE'), nullable=True)
    # Authenticated user id
    user_id: Mapped[int] = mapped_column(ForeignKey("oauth2_user.id", ondelete='CASCADE'), nullable=False)
    # Authenticated client id
    client_id: Mapped[int] = mapped_column(ForeignKey("oauth2_client.id", ondelete="CASCADE"), nullable=False)
    # Control refresh token validity (only one valid refresh token per session) (client may be without refresh)
